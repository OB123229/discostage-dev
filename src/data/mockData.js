// Returns events where the concert is today through +14 days
export function getUpcomingEvents() {
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const cutoff = new Date(today);
  cutoff.setDate(today.getDate() + 14);
  return EVENTS.filter((e) => {
    const d = new Date(e.concertDate);
    return d >= today && d <= cutoff;
  });
}

// Returns videos whose linked event is within the 2-week window
export function getUpcomingVideos() {
  const upcomingIds = new Set(getUpcomingEvents().map((e) => e.id));
  return VIDEOS.filter((v) => upcomingIds.has(v.eventId));
}
